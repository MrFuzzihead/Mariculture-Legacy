package mariculture.mixins;

import net.minecraft.launchwrapper.IClassTransformer;

import org.objectweb.asm.ClassReader;
import org.objectweb.asm.ClassVisitor;
import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.MethodVisitor;
import org.objectweb.asm.Opcodes;

/**
 * Makes legacy {@code 1.7.10-}-prefixed Mariculture version ranges satisfiable by the
 * current bare-semver release line.
 *
 * <p>
 * Why a LaunchWrapper transformer instead of a mixin? FML parses each mod's dependencies
 * during mod discovery (the {@code @Mod} annotation via
 * {@code Loader.computeDependencies} in {@code FMLModContainer.bindMetadata}, and
 * {@code mcmod.info} via {@code MetadataCollection}) and checks them in
 * {@code Loader.sortModList()} immediately afterwards — before any mod is constructed and
 * therefore before late mixins are registered. Both parse paths populate the same
 * {@code ModMetadata} lists, so rewriting those lists after {@code bindMetadata} covers
 * {@code after:}, {@code required-after:}, and {@code before:} uniformly.
 *
 * <p>
 * Why not an early mixin? Mixin refuses to target a class that is already loaded when
 * the mixin config is prepared, and every class on this code path is already loaded by
 * then in production packs: {@code FMLModContainer} and the {@code versioning} classes
 * load during FML bootstrap, and {@code ModDiscoverer} also loads before early-mixin
 * preparation in production (it happened to load later in the dev environment, which is
 * why the mixin appeared to work there). A transformer registered by this coremod (see
 * {@link EarlyMixinsLoader#getASMTransformerClass()}) runs as each class is loaded,
 * after all coremods are instantiated, so it is not subject to that restriction.
 *
 * <p>
 * Two injection points, both delegating to {@code LegacyMaricultureRange}:
 * <ul>
 * <li>{@code FMLModContainer.bindMetadata} at return: rewrites that container's
 * {@code ModMetadata} lists. {@code FMLModContainer} is first created by FMLLoader after
 * coremod registration, so the transformer reliably catches it.
 * <li>{@code JarDiscoverer.discover} / {@code DirectoryDiscoverer.discover} at every
 * return: rewrites the metadata of every container found in that source. These classes
 * only load during mod discovery itself, so they are the fallback if
 * {@code FMLModContainer} was somehow loaded before the transformer registered.
 * </ul>
 * The rewrite is idempotent (an already-rewritten unbounded range has no range string),
 * so both points firing for the same mod is harmless.
 *
 * <p>
 * The actual rewrite rules live in {@code LegacyMaricultureRange} so they are
 * unit-testable; this class only contains the ASM plumbing. The helper is referenced from
 * the generated bytecode by name and only loads when a patched method first runs, by
 * which time the Mariculture jar is on the classpath.
 */
public class VersionParserTransformer implements IClassTransformer {

    private static final String FML_MOD_CONTAINER = "cpw/mods/fml/common/FMLModContainer";
    private static final String JAR_DISCOVERER = "cpw/mods/fml/common/discovery/JarDiscoverer";
    private static final String DIRECTORY_DISCOVERER = "cpw/mods/fml/common/discovery/DirectoryDiscoverer";
    private static final String HELPER_CLASS = "mariculture/core/lib/LegacyMaricultureRange";

    @Override
    public byte[] transform(String name, String transformedName, byte[] basicClass) {
        String target = internalName(name, transformedName);
        if (target == null) {
            return basicClass;
        }
        try {
            ClassReader reader = new ClassReader(basicClass);
            ClassWriter writer = new ClassWriter(reader, ClassWriter.COMPUTE_FRAMES);
            reader.accept(new ClassVisitor(Opcodes.ASM5, writer) {

                @Override
                public MethodVisitor visitMethod(int access, String methodName, String descriptor, String signature,
                    String[] exceptions) {
                    MethodVisitor methodVisitor = super.visitMethod(
                        access,
                        methodName,
                        descriptor,
                        signature,
                        exceptions);
                    if (FML_MOD_CONTAINER.equals(target)) {
                        if (!"bindMetadata".equals(methodName)
                            || !"(Lcpw/mods/fml/common/MetadataCollection;)V".equals(descriptor)) {
                            return methodVisitor;
                        }
                        return new MethodVisitor(Opcodes.ASM5, methodVisitor) {

                            @Override
                            public void visitInsn(int opcode) {
                                if (opcode == Opcodes.RETURN) {
                                    // LegacyMaricultureRange.rewriteModMetadata(modMetadata);
                                    visitVarInsn(Opcodes.ALOAD, 0);
                                    visitFieldInsn(
                                        Opcodes.GETFIELD,
                                        FML_MOD_CONTAINER,
                                        "modMetadata",
                                        "Lcpw/mods/fml/common/ModMetadata;");
                                    visitMethodInsn(
                                        Opcodes.INVOKESTATIC,
                                        HELPER_CLASS,
                                        "rewriteModMetadata",
                                        "(Lcpw/mods/fml/common/ModMetadata;)V",
                                        false);
                                }
                                super.visitInsn(opcode);
                            }
                        };
                    }
                    // JarDiscoverer / DirectoryDiscoverer: discover(...) returns the found containers.
                    if (!"discover".equals(methodName)
                        || !"(Lcpw/mods/fml/common/discovery/ModCandidate;Lcpw/mods/fml/common/discovery/ASMDataTable;)Ljava/util/List;"
                            .equals(descriptor)) {
                        return methodVisitor;
                    }
                    return new MethodVisitor(Opcodes.ASM5, methodVisitor) {

                        @Override
                        public void visitInsn(int opcode) {
                            if (opcode == Opcodes.ARETURN) {
                                // LegacyMaricultureRange.rewriteModContainers(foundMods);
                                visitInsn(Opcodes.DUP);
                                visitMethodInsn(
                                    Opcodes.INVOKESTATIC,
                                    HELPER_CLASS,
                                    "rewriteModContainers",
                                    "(Ljava/util/List;)V",
                                    false);
                            }
                            super.visitInsn(opcode);
                        }
                    };
                }
            }, 0);
            return writer.toByteArray();
        } catch (Throwable t) {
            // Never break startup for an optimization: fall back to the unpatched class
            // (i.e. the original issue #4 behaviour) and say so loudly.
            System.err.println(
                "[Mariculture] Failed to patch " + target + " for legacy version ranges; continuing unpatched");
            t.printStackTrace();
            return basicClass;
        }
    }

    private static String internalName(String name, String transformedName) {
        for (String candidate : new String[] { name, transformedName }) {
            if (candidate == null) {
                continue;
            }
            String internal = candidate.replace('.', '/');
            if (FML_MOD_CONTAINER.equals(internal) || JAR_DISCOVERER.equals(internal)
                || DIRECTORY_DISCOVERER.equals(internal)) {
                return internal;
            }
        }
        return null;
    }
}
